#!/usr/bin/env python3
"""
dev/help_text.py — the help popup's text as screen codes.
Owner: doc/modules/help.md

Reads src/help.txt (the cheat sheet as the user reads it: plain text,
one window line per line, at most MAX_COL characters) and writes
src/help_text.s: HELP_LINES and help_text, each line a length byte and
its screen codes in the lower/upper character set.  A line too long, or
a character the set has no glyph for, stops it (HelpTextError, naming
the line).

    python3 dev/help_text.py [--out DIR]
"""
import argparse
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "src" / "help.txt"
OUTPUT = "help_text.s"
MAX_COL = 37                    # the window's text columns (help.md § The window)

# Screen codes of the lower/upper set for the characters that are not
# letters or $20-$3F (cse_io.md § Character Encoding Reference).
_SPECIAL = {"@": 0x00, "[": 0x1B, "£": 0x1C, "]": 0x1D, "^": 0x1E, "↑": 0x1E,
            "←": 0x1F}


class HelpTextError(ValueError):
    pass


def encode(line):
    """The screen codes of `line`; HelpTextError for a character without a glyph."""
    out = bytearray()
    for ch in line:
        if "a" <= ch <= "z":
            out.append(ord(ch) - 0x60)
        elif "A" <= ch <= "Z":
            out.append(ord(ch))
        elif " " <= ch <= "?":
            out.append(ord(ch))
        elif ch in _SPECIAL:
            out.append(_SPECIAL[ch])
        else:
            raise HelpTextError(f"no glyph for {ch!r}")
    return bytes(out)


def load(text):
    """The text's lines (blank ones kept, the final newline dropped), each
    checked; HelpTextError names the line."""
    lines = text.split("\n")
    if lines and lines[-1] == "":
        lines.pop()
    for n, line in enumerate(lines, 1):
        if len(line) > MAX_COL:
            raise HelpTextError(f"help.txt line {n}: {len(line)} characters, at most {MAX_COL}")
        try:
            encode(line)
        except HelpTextError as err:
            raise HelpTextError(f"help.txt line {n}: {err}") from None
    return lines


def render(lines):
    """src/help_text.s for `lines`."""
    out = ["; help_text.s",
           "; Generated by dev/help_text.py from src/help.txt – DO NOT EDIT BY HAND",
           ";",
           "; The help popup's text (doc/modules/help.md § The text): HELP_LINES",
           "; lines, each a length byte and its screen codes (the lower/upper set).",
           "",
           "        .export help_text, HELP_LINES",
           "",
           f"HELP_LINES = {len(lines)}",
           "",
           '.segment "KDATA"',
           "help_text:"]
    for line in lines:
        codes = encode(line)
        values = ", ".join([str(len(codes))] + [f"${c:02X}" for c in codes])
        out.append(f"        .byte {values}" + (f"    ; {line}" if line else ""))
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    ap.add_argument("--out", default=str(ROOT / "src"), help="output directory")
    args = ap.parse_args(argv)
    try:
        lines = load(SOURCE.read_text(encoding="utf-8"))
    except HelpTextError as err:
        sys.exit(f"help_text.py: {err}")
    path = pathlib.Path(args.out) / OUTPUT
    path.write_text(render(lines))
    print(f"wrote {path} ({len(lines)} lines)")


if __name__ == "__main__":
    main()
